namespace hahahalib
{
//---------------------------------------------------------------------------
template <typename T>
class hahaha_rectangle
{
public:
	// 建構物件並初始化預設狀態。
	hahaha_rectangle();
    // 建構物件並初始化預設狀態。
    hahaha_rectangle(
        const T& x1,  // 左上或起點的 X 座標。
        const T& y1,  // 左上或起點的 Y 座標。
        const T& x2,  // 右下或終點的 X 座標。
        const T& y2,  // 右下或終點的 Y 座標。
    	bool normalize = false  // 建構時是否先自動整理座標順序。
    );
	// 解構物件並釋放相關資源。
	~hahaha_rectangle();

	// 以既有物件內容建構新的物件實例。
	hahaha_rectangle(const hahaha_rectangle<T>& hr);
    // 以移動方式建構物件並接手既有資源。
    hahaha_rectangle(hahaha_rectangle<T>&& hr) noexcept;
	// 複製指派目前物件內容。
	hahaha_rectangle& operator=(const hahaha_rectangle<T>& hr);
    // 移動指派目前物件內容。
    hahaha_rectangle& operator=(hahaha_rectangle<T>&& hr) noexcept;
	// 複製來源物件的內部狀態。
	void Copy(const hahaha_rectangle<T>& hr);
    // 接手來源物件的內部資源。
    void Move(hahaha_rectangle<T>&& hr) noexcept;
public:
	// 重設內部狀態。
	int Reset();
public:
	// 計算目前圖形的寬度。
	T Width();
	// 計算目前圖形的高度。
	T Height();
	// 計算目前圖形的寬度。
	T Width() const;
	// 計算目前圖形的高度。
	T Height() const;

public:
    T X1_;
    T Y1_;
    T X2_;
    T Y2_;
public:
    // 整理座標順序，確保左上與右下定義正確。
    void Normalize();
public:
public:
public:
};



//---------------------------------------------------------------------------
} // hahahalib
//---------------------------------------------------------------------------

